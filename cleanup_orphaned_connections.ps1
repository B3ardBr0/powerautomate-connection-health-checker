<#
.SYNOPSIS
    Safely cleanup orphaned Power Automate connections that are not used by any flows.

.DESCRIPTION
    This script helps identify and delete orphaned connections based on age criteria.
    It reads the CSV output from check_connection_health.ps1 and provides an
    interactive interface to review and delete old/unused connections.

    Features:
    - Filter orphaned connections by minimum age
    - Interactive review of each connection before deletion
    - Detailed connection information display
    - Safe deletion with confirmation
    - Summary report of deletions
    - Dry-run mode for testing

.PARAMETER CsvPath
    Path to the ConnectionHealth CSV file generated by check_connection_health.ps1
    Supports wildcards (e.g., "ConnectionHealth_*.csv")

.PARAMETER MinimumAgeDays
    Minimum age in days for connections to be considered for deletion (default: 180)
    Only connections older than this will be shown for review

.PARAMETER DryRun
    If specified, shows what would be deleted without actually deleting anything

.PARAMETER AutoConfirm
    If specified, deletes all matching connections without prompting (DANGEROUS!)

.EXAMPLE
    .\cleanup_orphaned_connections.ps1
    Interactive cleanup of connections older than 180 days

.EXAMPLE
    .\cleanup_orphaned_connections.ps1 -MinimumAgeDays 365
    Cleanup connections older than 1 year

.EXAMPLE
    .\cleanup_orphaned_connections.ps1 -DryRun
    See what would be deleted without actually deleting

.EXAMPLE
    .\cleanup_orphaned_connections.ps1 -CsvPath "ConnectionHealth_20251012_115418.csv" -MinimumAgeDays 90
    Use specific CSV and cleanup connections older than 90 days

.NOTES
    Created by wjmaritz.dev
    Requires: Microsoft.PowerApps.Administration.PowerShell module

    IMPORTANT: This script DELETES connections. Use with caution!
#>

param(
    [Parameter(Mandatory=$false)]
    [string]$CsvPath,

    [Parameter(Mandatory=$false)]
    [int]$MinimumAgeDays = 180,

    [Parameter(Mandatory=$false)]
    [switch]$DryRun,

    [Parameter(Mandatory=$false)]
    [switch]$AutoConfirm
)

# Check and import required modules
$requiredModules = @(
    'Microsoft.PowerApps.Administration.PowerShell',
    'Microsoft.PowerApps.PowerShell'
)

Write-Host "=== Orphaned Connection Cleanup Tool ===" -ForegroundColor Cyan
Write-Host ""

foreach ($module in $requiredModules) {
    if (!(Get-Module -ListAvailable -Name $module)) {
        Write-Host "Installing module: $module" -ForegroundColor Yellow
        Install-Module -Name $module -Force -AllowClobber -Scope CurrentUser
    }
    Import-Module $module -ErrorAction Stop
}

# Connect to Power Platform
Write-Host "Connecting to Power Platform..." -ForegroundColor Yellow
try {
    Add-PowerAppsAccount
}
catch {
    Write-Error "Failed to connect to Power Platform. Error: $_"
    exit 1
}

Write-Host "Successfully connected!" -ForegroundColor Green
Write-Host ""

# Find CSV file if not specified
if (!$CsvPath) {
    Write-Host "Looking for recent ConnectionHealth CSV files..." -ForegroundColor Yellow
    $csvFiles = Get-ChildItem -Path $PSScriptRoot -Filter "ConnectionHealth_*.csv" | Sort-Object LastWriteTime -Descending

    if ($csvFiles.Count -eq 0) {
        Write-Error "No ConnectionHealth CSV files found. Please run check_connection_health.ps1 -IncludeOrphaned first."
        exit 1
    }

    $CsvPath = $csvFiles[0].FullName
    Write-Host "Using most recent CSV: $($csvFiles[0].Name)" -ForegroundColor Green
    Write-Host ""
}
else {
    # Handle wildcards
    if ($CsvPath -like "*`**") {
        $resolvedFiles = Get-ChildItem -Path $PSScriptRoot -Filter $CsvPath | Sort-Object LastWriteTime -Descending
        if ($resolvedFiles.Count -gt 0) {
            $CsvPath = $resolvedFiles[0].FullName
            Write-Host "Resolved to: $($resolvedFiles[0].Name)" -ForegroundColor Green
        }
        else {
            Write-Error "No files matching pattern '$CsvPath' found."
            exit 1
        }
    }
}

# Load CSV data
Write-Host "Loading connection data from CSV..." -ForegroundColor Yellow
try {
    $allConnections = Import-Csv -Path $CsvPath
    Write-Host "Loaded $($allConnections.Count) total connections" -ForegroundColor Green
}
catch {
    Write-Error "Failed to load CSV file. Error: $_"
    exit 1
}

# Filter for orphaned connections
$orphanedConnections = $allConnections | Where-Object { $_.IsOrphaned -eq "True" }
Write-Host "Found $($orphanedConnections.Count) orphaned connections" -ForegroundColor White
Write-Host ""

# Filter by age
Write-Host "Filtering connections older than $MinimumAgeDays days..." -ForegroundColor Yellow
$oldConnections = $orphanedConnections | Where-Object {
    if ($_.CreatedDate) {
        $createdDate = [DateTime]::Parse($_.CreatedDate)
        $age = ((Get-Date) - $createdDate).Days
        $age -ge $MinimumAgeDays
    }
    else {
        $false  # Skip if no creation date
    }
}

if ($oldConnections.Count -eq 0) {
    Write-Host "No orphaned connections older than $MinimumAgeDays days found." -ForegroundColor Green
    Write-Host "Nothing to clean up!" -ForegroundColor Green
    exit 0
}

Write-Host "Found $($oldConnections.Count) orphaned connections older than $MinimumAgeDays days" -ForegroundColor Cyan
Write-Host ""

# Display summary
Write-Host "=== Connections to Review ===" -ForegroundColor Cyan
$oldConnections | ForEach-Object {
    $createdDate = [DateTime]::Parse($_.CreatedDate)
    $age = ((Get-Date) - $createdDate).Days
    $_ | Add-Member -NotePropertyName "AgeDays" -NotePropertyValue $age -Force
}

$oldConnections | Sort-Object AgeDays -Descending | Select-Object -First 10 ConnectionName, ConnectorName, CreatedBy, CreatedDate, AgeDays | Format-Table -AutoSize

if ($oldConnections.Count -gt 10) {
    Write-Host "... and $($oldConnections.Count - 10) more" -ForegroundColor Gray
}
Write-Host ""

# Dry run mode
if ($DryRun) {
    Write-Host "=== DRY RUN MODE ===" -ForegroundColor Yellow
    Write-Host "The following $($oldConnections.Count) connections would be deleted:" -ForegroundColor Yellow
    Write-Host ""
    $oldConnections | Sort-Object AgeDays -Descending | Format-Table ConnectionName, ConnectorName, CreatedBy, AgeDays -AutoSize
    Write-Host ""
    Write-Host "No connections were deleted (dry run mode)." -ForegroundColor Green
    Write-Host "Remove -DryRun flag to actually delete connections." -ForegroundColor Yellow
    exit 0
}

# Confirm before proceeding
if (!$AutoConfirm) {
    Write-Host "WARNING: You are about to review and potentially DELETE $($oldConnections.Count) orphaned connections." -ForegroundColor Red
    Write-Host ""
    $confirm = Read-Host "Do you want to proceed with interactive review? (Y/N)"

    if ($confirm -ne 'Y' -and $confirm -ne 'y') {
        Write-Host "Cleanup cancelled." -ForegroundColor Yellow
        exit 0
    }
}

# Interactive deletion
Write-Host ""
Write-Host "=== Interactive Review ===" -ForegroundColor Cyan
Write-Host ""

$deletedCount = 0
$skippedCount = 0
$failedCount = 0
$deletionLog = @()

foreach ($connection in $oldConnections) {
    $createdDate = [DateTime]::Parse($connection.CreatedDate)
    $age = ((Get-Date) - $createdDate).Days

    Write-Host "----------------------------------------" -ForegroundColor Gray
    Write-Host "Connection: $($connection.ConnectionName)" -ForegroundColor Cyan
    Write-Host "  Type: $($connection.ConnectorName)" -ForegroundColor White
    Write-Host "  Created: $($connection.CreatedDate) ($age days ago)" -ForegroundColor White
    Write-Host "  Created By: $($connection.CreatedBy)" -ForegroundColor White
    Write-Host "  Environment: $($connection.Environment)" -ForegroundColor White
    Write-Host ""

    # Ask for confirmation (unless AutoConfirm is set)
    if ($AutoConfirm) {
        $response = 'Y'
    }
    else {
        $response = Read-Host "Delete this connection? (Y/N/Q to quit)"
    }

    if ($response -eq 'Q' -or $response -eq 'q') {
        Write-Host "Cleanup cancelled by user." -ForegroundColor Yellow
        break
    }

    if ($response -eq 'Y' -or $response -eq 'y') {
        try {
            # Attempt deletion
            Write-Host "  Deleting..." -ForegroundColor Yellow
            Remove-AdminPowerAppConnection -EnvironmentName $connection.EnvironmentId -ConnectionName $connection.ConnectionId

            Write-Host "  DELETED" -ForegroundColor Green
            $deletedCount++

            $deletionLog += [PSCustomObject]@{
                ConnectionName = $connection.ConnectionName
                ConnectorName = $connection.ConnectorName
                CreatedBy = $connection.CreatedBy
                AgeDays = $age
                Environment = $connection.Environment
                Status = "Deleted"
                Timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
            }
        }
        catch {
            Write-Host "  FAILED: $($_.Exception.Message)" -ForegroundColor Red
            $failedCount++

            $deletionLog += [PSCustomObject]@{
                ConnectionName = $connection.ConnectionName
                ConnectorName = $connection.ConnectorName
                CreatedBy = $connection.CreatedBy
                AgeDays = $age
                Environment = $connection.Environment
                Status = "Failed: $($_.Exception.Message)"
                Timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
            }
        }
    }
    else {
        Write-Host "  SKIPPED" -ForegroundColor Gray
        $skippedCount++
    }

    Write-Host ""
}

# Summary
Write-Host "========================================" -ForegroundColor Cyan
Write-Host "=== Cleanup Summary ===" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan
Write-Host ""
Write-Host "Connections reviewed: $($oldConnections.Count)" -ForegroundColor White
Write-Host "Deleted: $deletedCount" -ForegroundColor Green
Write-Host "Skipped: $skippedCount" -ForegroundColor Yellow
Write-Host "Failed: $failedCount" -ForegroundColor Red
Write-Host ""

# Export deletion log
if ($deletionLog.Count -gt 0) {
    $logPath = Join-Path $PSScriptRoot "ConnectionCleanupLog_$(Get-Date -Format 'yyyyMMdd_HHmmss').csv"
    $deletionLog | Export-Csv -Path $logPath -NoTypeInformation
    Write-Host "Deletion log exported to: $logPath" -ForegroundColor Green
}

Write-Host ""
Write-Host "Cleanup completed!" -ForegroundColor Cyan
Write-Host "Created by wjmaritz.dev" -ForegroundColor Gray
